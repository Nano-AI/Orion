#!/usr/bin/env python3
"""Writes the shim's field tables from orion.h.

    gen_fields.py <orion.h> <fields.inc> <mask_fields.inc>

One line per member C# may read or write by name:
    F(name, float)  F(name, int)   a scalar
    A(name, N)                     float name[N]
fields.inc is OrionAdjustments, mask_fields.inc is OrionMaskComponent (one row
of the mask group). Struct members (masks, spots, curves) and unsigned ones
(brush_revision, which the shim owns) are skipped: they need real types.
Regenerated on every native build so the tables cannot drift from the header.
"""
import re
import sys

header, out, mask_out = sys.argv[1], sys.argv[2], sys.argv[3]
text = open(header).read()
defines = dict(re.findall(r"#define\s+(\w+)\s+\(?(\d+)\)?", text))


def members(struct):
    match = re.search(r"typedef struct %s \{(.*?)\} %s;" % (struct, struct), text, re.S)
    if not match:
        sys.exit(f"gen_fields: {struct} not found in {header}")
    body = re.sub(r"/\*.*?\*/|//[^\n]*", "", match.group(1), flags=re.S)
    lines, scalars = [], 0
    for decl in (" ".join(d.split()) for d in body.split(";")):
        m = re.fullmatch(r"(float|int32_t|int)\s+(.+)", decl)
        if not m:
            continue
        kind = "float" if m.group(1) == "float" else "int"
        for name in (n.strip() for n in m.group(2).split(",")):
            array = re.fullmatch(r"(\w+)\[(\w+)\]", name)
            if array and kind == "float":
                size = defines.get(array.group(2), array.group(2))
                if not size.isdigit():
                    sys.exit(f"gen_fields: cannot size {name}")
                lines.append(f"A({array.group(1)}, {size})")
            elif re.fullmatch(r"\w+", name):
                lines.append(f"F({name}, {kind})")
                scalars += 1
    return lines, scalars


def write(path, lines):
    open(path, "w").write("// Generated by gen_fields.py from orion.h. Do not edit.\n" + "\n".join(lines) + "\n")


lines, scalars = members("OrionAdjustments")
if scalars < 50:
    sys.exit(f"gen_fields: only {scalars} scalars found — has orion.h changed shape?")
mask, mask_scalars = members("OrionMaskComponent")
if mask_scalars < 20:
    sys.exit(f"gen_fields: only {mask_scalars} mask fields found — has orion.h changed shape?")
write(out, lines)
write(mask_out, mask)
print(f"gen_fields: {scalars} scalars, {len(lines) - scalars} arrays, {mask_scalars} mask fields")
